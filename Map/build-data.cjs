// Combine the GeoJSON map data and farmer profiles into one JavaScript file so the dashboard can load them directly without using fetch()
const fs = require("node:fs");
const path = require("node:path");
const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(__dirname, name), "utf8"));
// The summary export stores its field names in the first row.
const [headers, ...summary] = read("data/MDB_Summary.json");
const locations = read("data/MDB_Towns_Rivers.json");
const d3 = require("../assets/vendor/d3/d3.min.js");
const statisticalRegions = read("data/MDB_ABS_SA3.geojson");
// D3 uses the opposite exterior-ring winding to RFC 7946 GeoJSON.
const containsRegions = structuredClone(statisticalRegions);
for (const feature of containsRegions.features) {
  const polygons = feature.geometry.type === "MultiPolygon"
    ? feature.geometry.coordinates : [feature.geometry.coordinates];
  for (const polygon of polygons) {
    if (d3.geoArea({ type: "Polygon", coordinates: polygon }) > 2 * Math.PI)
      polygon.forEach((ring) => ring.reverse());
  }
}
const towns = {
  type: "FeatureCollection",
  features: summary.map((row) => {
    const properties = Object.fromEntries(
      Object.entries(headers).map(([key, name]) => [name, row[key]]),
    );
    const location = locations.find((town) =>
      town.Town === properties.Town && town.State === properties.State);
    if (!location || !Number.isFinite(location.Longitude) || !Number.isFinite(location.Latitude)) {
      throw new Error(`Missing coordinates for ${properties.Town}, ${properties.State}`);
    }
    const matches = containsRegions.features.filter((region) =>
      d3.geoContains(region, [location.Longitude, location.Latitude]));
    if (matches.length !== 1) throw new Error(`Expected one ABS SA3 region for ${properties.Town}`);
    properties["ABS SA3 region"] = matches[0].properties.sa3_name_2021;
    properties["ABS SA3 code"] = matches[0].properties.sa3_code_2021;
    return {
      type: "Feature",
      properties,
      geometry: { type: "Point", coordinates: [location.Longitude, location.Latitude] },
    };
  }),
};
const writeGeoJSON = (name, collection) => fs.writeFileSync(
  path.join(__dirname, "data", name), JSON.stringify(collection, null, 2) + "\n",
);
writeGeoJSON("MDB_Summary.geojson", towns);
writeGeoJSON("MDB_Towns.geojson", towns);

// Summary regions have town locations, but no supplied polygon boundaries.
const regionGroups = new Map();
for (const town of towns.features) {
  const name = town.properties.Region;
  if (!regionGroups.has(name)) regionGroups.set(name, []);
  regionGroups.get(name).push(town);
}
const summaryRegions = {
  type: "FeatureCollection",
  features: [...regionGroups].sort(([a], [b]) => a.localeCompare(b)).map(([name, members]) => ({
    type: "Feature",
    properties: {
      Region: name,
      States: [...new Set(members.map((town) => town.properties.State))].sort(),
      Towns: members.map((town) => town.properties.Town).sort(),
      "Town count": members.length,
      "Geometry description": "Member town locations; not a region boundary",
    },
    geometry: { type: "MultiPoint", coordinates: members.map((town) => town.geometry.coordinates) },
  })),
};
writeGeoJSON("MDB_Regions.geojson", summaryRegions);
const data = {
  geojson: read("mdb_geo_json.json"),
  farmers: read("farmers.json"),
  towns,
  statisticalRegions,
};
// Preserve the supplied water plan polygons as a separately named GeoJSON file.
writeGeoJSON("MDB_Water_Resource_Regions.geojson", data.geojson);
fs.writeFileSync(
  path.join(__dirname, "dashboard-data.js"),
  "// Generated by Map/build-data.cjs; edit the source JSON files.\n" +
    "window.basinData = " + JSON.stringify(data) + ";\n",
);
console.log("Bundled " + data.geojson.features.length + " regions and " + data.farmers.length + " profiles.");
console.log(`Exported ${towns.features.length} towns, ${summaryRegions.features.length} summary regions (MultiPoint), and ${data.geojson.features.length} water resource regions (polygons).`);
